package net.atlasauth.pca.verifier

import java.nio.file.Files
import java.nio.file.Path
import java.util.zip.GZIPInputStream
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Differential kill tests of SafeRegex.kt against the TS reference (safe-regex.ts, predicates.ts isSafeRegexSource,
 * regex-budget.ts): compiled sizes, full-match results (true / false / refused) over a pattern corpus crossed with
 * boundary-probing subjects, the step boundary, the safe-source guard (incl. the 22-bit cost budget) and the per-document
 * budget. Golden data: test-data/killRegex.json.gz, generated by tools/pca-audit/kotlin-mutate/killRegex-oracle-gen.mjs.
 */
class KillRegexTest {
    companion object {
        @Suppress("UNCHECKED_CAST")
        val data: Map<String, Any?> by lazy {
            GZIPInputStream(Files.newInputStream(Path.of("test-data/killRegex.json.gz"))).use { Json.parseLenient(String(it.readAllBytes(), Charsets.UTF_8)) as Map<String, Any?> }
        }
        @Suppress("UNCHECKED_CAST") fun sec(k: String): List<List<Any?>> = data[k] as List<List<Any?>>
        fun int(o: Any?): Int = (o as Json.Num).raw.toInt()
        fun lng(o: Any?): Long = (o as Json.Num).raw.toLong()
    }

    @Test fun fullMatchCorpus() {
        var n = 0
        for (e in sec("fm")) {
            val p = e[0] as String
            @Suppress("UNCHECKED_CAST") val subs = e[1] as List<String>
            val rs = e[2] as String
            assertEquals(p, subs.size, rs.length)
            for (i in subs.indices) {
                val want: Boolean? = when (rs[i]) { '1' -> true; '0' -> false; else -> null }
                val got = SafeRegex.fullMatch(p, subs[i])
                if (want != got) assertEquals("/$p/ on ${subs[i].map { it.code }}", want, got)
                n++
            }
        }
        assertTrue(n > 100000)
    }

    @Test fun compiledSizes() {
        for (e in sec("size")) {
            val p = e[0] as String
            val want = int(e[1])
            val c = SafeRegex.compile(p)
            if (want < 0) { if (c != null) assertNull("/$p/", c) } else { assertNotNull("/$p/", c); assertEquals("/$p/", want, c!!.size()) }
        }
    }

    @Test fun matchStepBoundary() {
        for (e in sec("steps")) {
            val p = e[0] as String
            val n = int(e[1])
            val want: Boolean? = when (int(e[2])) { 1 -> true; 0 -> false; else -> null }
            assertEquals("/${p.take(20)}/ n=$n", want, SafeRegex.fullMatch(p, "a".repeat(n)))
        }
    }

    @Test fun safeSourceGuard() {
        for (e in sec("safe")) { val got = SafeRegex.isSafeSource(e[0] as String); if (got != e[1] as Boolean) assertEquals("/${e[0]}/", e[1] as Boolean, got) }
        assertFalse(SafeRegex.isSafeSource(null))
        assertNull(SafeRegex.compile(null))
        assertNull(SafeRegex.fullMatch(null, "a"))
    }

    @Test fun budgetSequences() {
        @Suppress("UNCHECKED_CAST") val bs = data["budgets"] as List<Map<String, Any?>>
        for ((k, b) in bs.withIndex()) {
            val budget = SafeRegex.Budget()
            @Suppress("UNCHECKED_CAST") val ops = b["ops"] as List<List<Any?>>
            @Suppress("UNCHECKED_CAST") val res = b["res"] as List<Boolean>
            for ((i, op) in ops.withIndex()) assertEquals("budget #$k op $i", res[i], budget.charge(op[0] as String, int(op[1])))
            @Suppress("UNCHECKED_CAST") val fin = b["fin"] as List<Any?>
            assertEquals("budget #$k evaluations", int(fin[0]), budget.evaluations)
            assertEquals("budget #$k chars", int(fin[1]), budget.chars)
            assertEquals("budget #$k steps", lng(fin[2]), budget.steps)
            assertEquals("budget #$k refusals", int(fin[3]), budget.refusals)
        }
    }

    @Test fun constants() {
        assertEquals(4096, SafeRegex.MAX_NFA_INSTRUCTIONS)
        assertEquals(64, SafeRegex.MAX_REPEAT)
        assertEquals(2_000_000L, SafeRegex.MAX_MATCH_STEPS)
        assertEquals(64, SafeRegex.MAX_REGEX_EVALUATIONS_PER_DOCUMENT)
        assertEquals(8192, SafeRegex.MAX_REGEX_SOURCE_CHARS_PER_DOCUMENT)
        assertEquals(5_000_000L, SafeRegex.MAX_REGEX_STEPS_PER_DOCUMENT)
    }

    // ---- scopes: withBudget / charge ----
    @Test fun chargeOutsideAnyScopeIsFreshEveryTime() {
        for (i in 0 until 100) assertTrue(SafeRegex.charge("a", 1))
        assertFalse(SafeRegex.charge("a(", 1))
        assertTrue(SafeRegex.charge("a", 1))
    }

    @Test fun withBudgetSharesOneDocumentAndNests() {
        val r = SafeRegex.withBudget {
            var ok = 0
            for (i in 0 until 40) if (SafeRegex.charge("a", 0)) ok++
            val inner = SafeRegex.withBudget {
                var ok2 = 0
                for (i in 0 until 40) if (SafeRegex.charge("a", 0)) ok2++
                ok2
            }
            listOf(ok, inner, if (SafeRegex.charge("a", 0)) 1 else 0)
        }
        assertEquals(listOf(40, 24, 0), r)
        // a fresh scope afterwards starts from zero again
        assertEquals(64, SafeRegex.withBudget { (0 until 70).count { SafeRegex.charge("a", 0) } })
    }

    @Test fun withBudgetReturnsTheValueAndClearsTheScopeOnThrow() {
        assertEquals("v", SafeRegex.withBudget { "v" })
        try {
            SafeRegex.withBudget { for (i in 0 until 10) SafeRegex.charge("a", 0); throw IllegalStateException("boom") }
        } catch (e: IllegalStateException) { /* expected */ }
        assertEquals(64, SafeRegex.withBudget { (0 until 70).count { SafeRegex.charge("a", 0) } })
        // outside a scope the poison of an earlier scope is gone
        SafeRegex.withBudget { for (i in 0 until 70) SafeRegex.charge("a", 0) }
        assertTrue(SafeRegex.charge("a", 0))
    }

    @Test fun poisonedBudgetRefusesLaterCheapPatterns() {
        SafeRegex.withBudget {
            assertFalse(SafeRegex.charge("a", 5_000_000))
            assertFalse(SafeRegex.charge("a", 0))
        }
    }

    // ---- helpers ----
    @Test fun ceilLog2IsExact() {
        val want = mapOf(2L to 1, 3L to 2, 4L to 2, 5L to 3, 8L to 3, 9L to 4, 64L to 6, 65L to 7, 1L shl 40 to 40, (1L shl 40) + 1 to 41, (1L shl 62) to 62)
        for ((n, w) in want) assertEquals("ceilLog2($n)", w, SafeRegex.ceilLog2(n))
    }

    private fun rs(vararg p: Pair<Int, Int>): List<IntArray> = p.map { intArrayOf(it.first, it.second) }
    private fun flat(a: Array<IntArray>): List<Int> = a.flatMap { listOf(it[0], it[1]) }

    @Test fun normalizeSortsAndMergesAdjacent() {
        assertEquals(listOf(1, 7, 10, 12), flat(SafeRegex.normalize(rs(5 to 7, 1 to 2, 3 to 4, 10 to 12, 11 to 11))))
        assertEquals(listOf(1, 2, 4, 5), flat(SafeRegex.normalize(rs(4 to 5, 1 to 2))))
        assertEquals(listOf(1, 5), flat(SafeRegex.normalize(rs(1 to 5, 2 to 3))))
        assertEquals(listOf(1, 5), flat(SafeRegex.normalize(rs(1 to 3, 3 to 5))))
        assertEquals(listOf(1, 5), flat(SafeRegex.normalize(rs(1 to 3, 4 to 5))))
        assertEquals(listOf(1, 3, 5, 6), flat(SafeRegex.normalize(rs(1 to 3, 5 to 6))))
        assertEquals(listOf<Int>(), flat(SafeRegex.normalize(rs())))
        assertEquals(listOf(0, 0), flat(SafeRegex.normalize(rs(0 to 0))))
        // the inputs are not mutated
        val input = rs(1 to 2, 3 to 4)
        SafeRegex.normalize(input)
        assertEquals(listOf(1, 2, 3, 4), input.flatMap { listOf(it[0], it[1]) })
    }

    @Test fun complementCoversTheGapsOfTheCodeUnitSpace() {
        assertEquals(listOf(0, 0xffff), flat(SafeRegex.complement(arrayOf())))
        assertEquals(listOf<Int>(), flat(SafeRegex.complement(arrayOf(intArrayOf(0, 0xffff)))))
        assertEquals(listOf(6, 9), flat(SafeRegex.complement(arrayOf(intArrayOf(0, 5), intArrayOf(10, 0xffff)))))
        assertEquals(listOf(0, 2, 5, 0xffff), flat(SafeRegex.complement(arrayOf(intArrayOf(3, 4)))))
        assertEquals(listOf(0, 0xfffe), flat(SafeRegex.complement(arrayOf(intArrayOf(0xffff, 0xffff)))))
        assertEquals(listOf(1, 0xffff), flat(SafeRegex.complement(arrayOf(intArrayOf(0, 0)))))
        assertEquals(listOf(0, 0, 2, 0xffff), flat(SafeRegex.complement(arrayOf(intArrayOf(1, 1)))))
        assertEquals(listOf(2, 2), flat(SafeRegex.complement(arrayOf(intArrayOf(0, 1), intArrayOf(3, 0xffff)))))
        // unsorted / adjacent input is normalised first
        assertEquals(listOf(0, 1, 6, 0xffff), flat(SafeRegex.complement(arrayOf(intArrayOf(4, 5), intArrayOf(2, 3)))))
    }

    @Test fun charSetBinarySearchAndNegation() {
        val set = SafeRegex.CharSet(arrayOf(intArrayOf(2, 3), intArrayOf(10, 10), intArrayOf(20, 30), intArrayOf(40, 41), intArrayOf(100, 200)), false)
        val inside = ((2..3) + (10..10) + (20..30) + (40..41) + (100..200)).toSet()
        for (c in 0..210) assertEquals("c=$c", c in inside, set.has(c))
        val neg = SafeRegex.CharSet(set.ranges, true)
        for (c in 0..210) assertEquals("neg c=$c", c !in inside, neg.has(c))
        assertFalse(SafeRegex.CharSet(arrayOf(), false).has(5))
        assertTrue(SafeRegex.CharSet(arrayOf(), true).has(5))
        val one = SafeRegex.CharSet(arrayOf(intArrayOf(7, 7)), false)
        assertTrue(one.has(7)); assertFalse(one.has(6)); assertFalse(one.has(8))
        val two = SafeRegex.CharSet(arrayOf(intArrayOf(1, 1), intArrayOf(9, 9)), false)
        for (c in 0..10) assertEquals("two c=$c", c == 1 || c == 9, two.has(c))
    }

    @Test fun runUsesTheProgramNotTheSource() {
        val re = SafeRegex.compile("a+b")!!
        assertEquals(true, SafeRegex.run(re, "aab"))
        assertEquals(false, SafeRegex.run(re, "aa"))
        assertEquals(false, SafeRegex.run(re, ""))
        assertEquals(6, re.size())
    }
}
