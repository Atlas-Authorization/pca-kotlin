package net.atlasauth.pca.verifier

import java.nio.file.Files
import java.nio.file.Path
import java.util.zip.GZIPInputStream
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Differential kill tests of Predicates.kt against the TS reference (predicates.ts): path resolution over many contexts,
 * every leaf operator over fields x operands (value and ref forms), `like` globs, `matches`, `member_of` closures (incl. the
 * 10,000-node bound and own `__proto__` members), groupings, the per-document regex budget, predicates and predicate lists.
 * Golden data: test-data/killPred.json.gz, generated by tools/pca-audit/kotlin-mutate/killPred-oracle-gen.mjs.
 */
class KillPredTest {
    companion object {
        @Suppress("UNCHECKED_CAST")
        val data: Map<String, Any?> by lazy {
            GZIPInputStream(Files.newInputStream(Path.of("test-data/killPred.json.gz"))).use { Json.parseLenient(String(it.readAllBytes(), Charsets.UTF_8)) as Map<String, Any?> }
        }
        @Suppress("UNCHECKED_CAST") fun sec(k: String): List<List<Any?>> = data[k] as List<List<Any?>>
        @Suppress("UNCHECKED_CAST") fun ctx(i: Any?): Map<String, Any?>? = (data["ctxs"] as List<Any?>)[(i as Json.Num).raw.toInt()] as Map<String, Any?>?
        fun tri(s: Any?): Predicates.Tri = when (s as String) { "T" -> Predicates.Tri.TRUE; "F" -> Predicates.Tri.FALSE; else -> Predicates.Tri.UNKNOWN }
    }

    private fun label(e: List<Any?>) = (try { Json.canonicalize(e[0]).take(160) } catch (x: RuntimeException) { "<deep>" }) + " @ctx" + (e[1] as Json.Num).raw
    private fun <T> check(e: List<Any?>, want: T, got: T) { if (want != got) assertEquals(label(e), want, got) }

    @Test fun resolvePathMatchesTheReference() {
        for (e in sec("rp")) {
            val r = Predicates.resolvePath(ctx(e[1]), e[0])
            check(e, e[2] as Boolean, r.found)
            if (r.found) check(e, Json.canonicalize(e[3]), Json.canonicalize(r.value))
            else if (r.value != null) assertNull(label(e), r.value)
        }
    }

    @Test fun conditionsMatchTheReference() {
        var n = 0
        for (e in sec("cond")) {
            val got = Predicates.evaluateConditionTri(e[0], ctx(e[1]))
            check(e, tri(e[2]), got)
            check(e, tri(e[2]) == Predicates.Tri.TRUE, Predicates.evaluateCondition(e[0], ctx(e[1])))
            n++
        }
        assertTrue(n > 100000)
    }

    @Test fun predicatesMatchTheReference() {
        for (e in sec("pred")) check(e, e[2] as Boolean, Predicates.predicateMatches(e[0], ctx(e[1])))
    }

    @Test fun predicateListsMatchTheReference() {
        for (e in sec("preds")) check(e, e[2] as Boolean, Predicates.evaluatePredicates(e[0], ctx(e[1])))
    }

    @Test fun globMatchTokens() {
        assertEquals(true, Predicates.globMatch("a*c", "abc"))
        assertEquals(true, Predicates.globMatch("a**c", "ac"))
        assertEquals(false, Predicates.globMatch("a*c", "ab"))
        assertEquals(true, Predicates.globMatch("a?c", "abc"))
        assertEquals(false, Predicates.globMatch("a?c", "ac"))
        assertEquals(true, Predicates.globMatch("a\\*c", "a*c"))
        assertEquals(false, Predicates.globMatch("a\\*c", "abc"))
        assertEquals(true, Predicates.globMatch("a\\\\c", "a\\c"))
        assertNull(Predicates.globMatch("abc\\", "abc"))
        assertNull(Predicates.globMatch("\\", ""))
        assertEquals(true, Predicates.globMatch("", ""))
        assertEquals(false, Predicates.globMatch("", "a"))
        assertEquals(true, Predicates.globMatch("*", ""))
        assertEquals(false, Predicates.globMatch("?", ""))
        assertEquals(true, Predicates.globMatch("*a*b*c*", "xxaxxbxxcxx"))
        assertEquals(false, Predicates.globMatch("*a*b*c*", "xxaxxcxxbxx"))
        assertEquals(false, Predicates.globMatch("a*a*a*b", "a".repeat(400)))
        assertEquals(true, Predicates.globMatch("a*a*a*b", "a".repeat(400) + "b"))
    }

    @Test fun constants() {
        assertEquals(512, Predicates.MAX_PATTERN_SUBJECT_LEN)
        assertEquals(512, Predicates.MAX_LIKE_PATTERN_LEN)
        assertEquals(200, Predicates.MAX_MATCHES_PATTERN_LEN)
        assertEquals(10_000, Predicates.MAX_MEMBER_CLOSURE_NODES)
        assertEquals(512, Predicates.MAX_RE_RESOURCE_LEN)
        assertFalse(Predicates.evaluateCondition(null, null))
    }
}
