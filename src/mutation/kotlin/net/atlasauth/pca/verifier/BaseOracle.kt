package net.atlasauth.pca.verifier

import java.nio.file.Files
import java.nio.file.Path
import java.util.zip.GZIPInputStream

/**
 * Streams a base oracle (test-data/base-*.json.gz: one case per line) and parses only the cases of one fn. Parsing a whole oracle
 * (the action registry one is 170 MB of JSON) ran the 2 GB surefire fork and the 1.5 GB PIT minions out of heap.
 */
object BaseOracle {
    private val FN = Regex("^\\{\"fn\":\"((?:[^\"\\\\]|\\\\.)*)\"")

    /** Corpora whose tests resolve their own {"$seed": label} placeholders (the label is the argument, not a key to materialize). */
    private val BESPOKE_SEEDS = setOf("ref-wallet", "ref-actions-signbuiltins-py", "ref-notary")

    /** Replaces every {"$seed": label[, "es256": true]} object by base64url(SHA-256("atlas-pca-conformance/" + label)), top bit of byte 0 cleared for es256. */
    @Suppress("UNCHECKED_CAST")
    fun resolveSeeds(v: Any?): Any? = when (v) {
        is List<*> -> v.map { resolveSeeds(it) }
        is Map<*, *> -> {
            val m = v as Map<String, Any?>
            val units = m["\$utf16"]
            val label = m["\$seed"]
            if (m.size == 1 && units is List<*>) units.map { (if (it is Json.Num) it.raw.toDouble() else (it as Number).toDouble()).toInt().toChar() }.joinToString("") // {"\$utf16": [code units]}: a lone surrogate
            else if (label is String && setOf("\$seed", "es256", "ec", "ed448").containsAll(m.keys)) {
                val md = java.security.MessageDigest.getInstance("SHA-256")
                val p = "atlas-pca-conformance/" + label
                val h1 = md.digest(p.toByteArray(Charsets.UTF_8))
                val h2 = md.digest((p + "/2").toByteArray(Charsets.UTF_8))
                val h3 = md.digest((p + "/3").toByteArray(Charsets.UTF_8))
                val all = h1 + h2 + h3
                val raw = when {
                    m["ec"] == "P-384" -> all.copyOf(48).also { it[0] = (it[0].toInt() and 0x7F).toByte() }
                    m["ec"] == "P-521" -> all.copyOf(66).also { it[0] = (it[0].toInt() and 0x01).toByte() }
                    m["ed448"] == true -> h1 + h2.copyOf(25)
                    else -> h1.also { if (m["es256"] == true) it[0] = (it[0].toInt() and 0x7F).toByte() }
                }
                java.util.Base64.getUrlEncoder().withoutPadding().encodeToString(raw)
            } else m.mapValuesTo(LinkedHashMap()) { resolveSeeds(it.value) }
        }
        else -> v
    }

    const val RSA = "ref-dpop-rsa"

    /** ref-dpop-rsa is generated by CI (never committed): PCA_DPOP_RSA_CORPUS, else test-data/. */
    fun corpusPath(file: String): Path {
        val env = System.getenv("PCA_DPOP_RSA_CORPUS")
        return if (file == "$RSA.json.gz" && !env.isNullOrEmpty()) Path.of(env) else Path.of("test-data/$file")
    }

    /** Corpora whose private-key cases are generated by CI (never committed) into <name>-gen.json.gz next to the main corpus (PCA_SECRET_CORPUS_DIR overrides the directory). */
    private val GEN = setOf("ref-oprf", "ref-core-frost-java", "ref-mpc-ot", "ref-attest-eat", "ref-abe", "ref-frost-dkg")

    fun genPath(module: String): Path {
        val env = System.getenv("PCA_SECRET_CORPUS_DIR")
        val dir = if (!env.isNullOrEmpty()) Path.of(env) else corpusPath("$module.json.gz").toAbsolutePath().parent
        return dir.resolve("$module-gen.json.gz")
    }

    /** The -gen corpus must exist when CI is "true"/"1" (generate with gen-secret-corpus.sh), else the calling test is skipped. */
    fun requireGen(module: String) {
        val p = genPath(module)
        val msg = "secret oracle corpus missing: $p (generate with gen-secret-corpus.sh or set PCA_SECRET_CORPUS_DIR)"
        val ci = System.getenv("CI")
        if (ci == "true" || ci == "1") org.junit.Assert.assertTrue(msg, Files.exists(p)) else org.junit.Assume.assumeTrue(msg, Files.exists(p))
    }

    private fun lines(file: String, each: (String) -> Unit) {
        val m = file.removeSuffix(".json.gz")
        val paths = listOf(corpusPath(file)) + if (m in GEN && Files.exists(genPath(m))) listOf(genPath(m)) else emptyList()
        for (p in paths) GZIPInputStream(Files.newInputStream(p), 1 shl 16).bufferedReader(Charsets.UTF_8).use { r -> r.lineSequence().forEach(each) }
    }

    /** The generator clock (epoch ms) of corpora committed before the header carried "clockMs". */
    const val FALLBACK_CLOCK_MS = 1_800_000_000_000.0

    /** The frozen clock a corpus header line (everything up to the opening bracket of "cases") records as "clockMs", else [FALLBACK_CLOCK_MS]. */
    fun clockOfHeader(header: String?): Double {
        if (header == null || !header.endsWith("[")) return FALLBACK_CLOCK_MS
        // the header ends inside the cases array: close it
        val v = (Json.parseLenient(header + "]}") as? Map<*, *>)?.get("clockMs")
        val d = (v as? Json.Num)?.raw?.toDoubleOrNull() ?: (v as? Number)?.toDouble()
        return if (d != null && d.isFinite()) d else FALLBACK_CLOCK_MS
    }

    /** The one clock accessor of the replays: the frozen clock of the corpus [file] (e.g. "ref-revoke.json.gz"). */
    fun clockMs(file: String): Double =
        clockOfHeader(GZIPInputStream(Files.newInputStream(corpusPath(file)), 1 shl 16).bufferedReader(Charsets.UTF_8).use { it.readLine() })

    /** The fixed case clock T0 the oracles stamp into their scripted cases (an instant of their own, apart from the frozen wall clock [clockMs]). */
    const val T0 = 1_800_000_000_000L

    /** [clockMs] as a whole-millisecond Long. */
    fun clockLong(file: String): Long = clockMs(file).toLong()

    /** [clockMs] spelled as a plain integer literal (for a corpus-style number). */
    fun clockText(file: String): String = java.math.BigDecimal(clockMs(file)).toPlainString()

    /** Every fn the oracle holds. */
    fun fns(file: String): Set<String> {
        val s = LinkedHashSet<String>()
        lines(file) { l -> FN.find(l)?.let { s.add(it.groupValues[1]) } }
        return s
    }

    /** The cases of [fn], parsed leniently ([normalize]: numbers spelled as JavaScript prints them). */
    @Suppress("UNCHECKED_CAST")
    fun cases(file: String, fn: String, normalize: Boolean = true): List<Map<String, Any?>> {
        val pre = "{\"fn\":" + Json.canonicalize(fn) + ","
        val out = ArrayList<Map<String, Any?>>()
        lines(file) { l ->
            if (l.startsWith(pre)) {
                val v = Json.parseLenient(l.removeSuffix(","))
                val n = if (normalize) IntentJs.normalize(v) else v
                out.add((if (file.removeSuffix(".json.gz") in BESPOKE_SEEDS) n else resolveSeeds(n)) as Map<String, Any?>)
            }
        }
        return out
    }
}
