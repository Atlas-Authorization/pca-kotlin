package net.atlasauth.pca.verifier

import java.nio.file.Files
import java.nio.file.Path
import java.util.zip.GZIPInputStream
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Differential kill tests of IntentV2.kt / IntentRevocation.kt against the TS reference (intent-v2.ts `decideIntentV2` /
 * `intentV2Active`, intent-revocation.ts `checkSessionRevocation` / `revocationEpochShapeError`): every reported v2 check
 * with its EXACT reason and the verifier-computed env, over the Intent Layer v2 vectors of the conformance core plus
 * targeted variants. Golden data: test-data/killV2.json.gz (gzip of the JSON), generated by tools/pca-audit/kotlin-mutate/killV2-oracle-gen.mjs.
 */
class KillV2Test {
    companion object {
        @Suppress("UNCHECKED_CAST")
        val data: Map<String, Any?> by lazy {
            GZIPInputStream(Files.newInputStream(Path.of("test-data/killV2.json.gz"))).use { Json.parseLenient(String(it.readAllBytes(), Charsets.UTF_8)) as Map<String, Any?> }
        }
        @Suppress("UNCHECKED_CAST") fun sec(k: String): List<Map<String, Any?>> = data[k] as List<Map<String, Any?>>
        @Suppress("UNCHECKED_CAST") fun m(o: Any?): Map<String, Any?> = o as Map<String, Any?>

        /**
         * Where Kotlin knowingly differs from the reference, its exact checks (`name|ok|reason`, one per reported check):
         * reason texts of other files (ActionSchema), suites this verifier does not implement (FN-DSA), JS-only object
         * semantics (`__proto__`), and inputs the wire check refuses before the v2 checks run (Kotlin's typed failure).
         */
        val KOTLIN: Map<String, String> = mapOf(
            "corpus/schema-note-too-long" to "schema|false|schema_violation: out_of_domain: 'action.params.note': longer than the declared max_len\nintent_session|true|null\naccumulators|true|null",
            "corpus/session-wire-not-object" to "schema|false|intent_session.schema names no schema this verifier accepts\nintent_session|false|intent_session error (fail closed): ClassCastException\n" +
                "accumulators|false|accumulators error (fail closed): ClassCastException\nfacts|false|facts: the W-B context is malformed: intent_session must be an object",
            "corpus/acc-state-own-proto-key" to "schema|true|null\nintent_session|true|null\naccumulators|false|no state for site-local accumulator 'trip_spend'",
            "corpus/session-root-fn-dsa-1024" to "schema|true|null\nintent_session|false|session root: principal alg: unsupported_suite: 'fn-dsa-1024'\naccumulators|false|session root: principal alg: unsupported_suite: 'fn-dsa-1024'",
            "corpus/session-root-fn-dsa-512" to "schema|true|null\nintent_session|false|session root: principal alg: unsupported_suite: 'fn-dsa-512'\naccumulators|false|session root: principal alg: unsupported_suite: 'fn-dsa-512'",
        )

        /** Kotlin names the exception class where the reference prints its message: compare up to the class name. */
        fun same(want: Any?, got: String?): Boolean {
            if (want == got) return true
            if (want !is String || got == null) return false
            val i = want.indexOf("error (fail closed): ")
            return i >= 0 && got.startsWith(want.substring(0, i + "error (fail closed): ".length))
        }

        fun ctxOf(c: Map<String, Any?>): IntentV2.Context? = if (c.containsKey("ctx")) IntentV2.Context.fromJson(c["ctx"]) else null
    }

    @Test fun decideMatchesTheReference() {
        val bad = ArrayList<String>()
        for (c in sec("decide")) {
            @Suppress("UNCHECKED_CAST")
            val d = IntentV2.decide(m(c["p"]), c["grant"] as Map<String, Any?>?, ctxOf(c), Json.asLong(c["now"]))
            val got = d.checks.joinToString("\n") { "${it.name}|${it.ok}|${it.reason}" }
            val kt = KOTLIN[c["name"]]
            var ok: Boolean
            if (kt != null) ok = kt == got
            else {
                val want = c["checks"] as List<*>
                ok = want.size == d.checks.size
                if (ok) for (i in want.indices) {
                    val w = want[i] as List<*>
                    val g = d.checks[i]
                    if (w[0] != g.name || w[1] != g.ok || !same(w[2], g.reason)) ok = false
                }
                if (Json.canonicalizeStrict(d.env) != c["env"]) ok = false
            }
            for (x in d.checks) if (x.ok != (x.reason == null)) ok = false
            if (!ok) bad.add("${c["name"]}:\n  want ${c["checks"]}\n  got  ${got.replace("\n", " ; ")}\n  env want ${c["env"]}\n  env got  ${Json.canonicalizeStrict(d.env)}")
        }
        assertTrue("${bad.size} mismatches:\n" + bad.joinToString("\n"), bad.isEmpty())
    }

    @Test fun revocationPrimitiveMatchesTheReference() {
        val bad = ArrayList<String>()
        for (c in sec("rev")) {
            val got = IntentRevocation.primitiveReason(c["input"])
            val want = if (c["reason"] == "NOT-OBJECT") "session revocation check error (fail closed)" else c["reason"]
            if (!same(want, got)) bad.add("${c["name"]}: want $want got $got")
            assertEquals(c["name"].toString(), got == null, IntentRevocation.checkPrimitive(c["input"]))
        }
        assertTrue("${bad.size} mismatches:\n" + bad.joinToString("\n"), bad.isEmpty())
    }

    @Test fun activeMatchesTheReference() {
        for (c in sec("active")) assertEquals(c["name"].toString(), c["want"], IntentV2.active(m(c["p"]), ctxOf(c)))
    }

    @Test fun epochShapeMatchesTheReference() {
        for (c in sec("shape")) assertEquals(c["name"].toString(), c["want"], IntentRevocation.revocationEpochShapeError(IntentJs.normalize(c["ep"])))
    }

    @Test fun jsTruthinessAndText() {
        for (c in sec("truthy")) assertEquals(c["name"].toString(), c["want"], IntentRevocation.truthy(IntentJs.normalize(c["v"])))
        assertEquals(false, IntentRevocation.truthy(Double.NaN))
        assertEquals(true, IntentRevocation.truthy(Double.POSITIVE_INFINITY))
        for (c in sec("jstext")) assertEquals(c["name"].toString(), c["want"], IntentRevocation.jsText(IntentJs.normalize(c["v"]), true))
        assertEquals("undefined", IntentRevocation.jsText(null, false))
        assertEquals("undefined", IntentRevocation.jsText("x", false))
        assertEquals("pca-intent:profile:p@3", IntentRevocation.profileRevocationId("p", "3"))
        assertEquals(listOf("session", "scope", "authority", "ids", "now", "max_age_ms", "last"), IntentRevocation.PRIMITIVE_PARAMS)
    }
}
