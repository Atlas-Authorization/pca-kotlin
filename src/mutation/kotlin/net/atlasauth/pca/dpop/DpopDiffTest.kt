    // ---- what the oracle cannot see ----

    @Test fun createdEdDsaProofVerifiesAndTamperingIsRefused() {
        val k = Keys.edFromSeed(ByteArray(32))
        val pub = linkedMapOf<String, Any?>("kty" to "OKP", "crv" to "Ed25519", "x" to k.id())
        val priv = LinkedHashMap(pub).apply { put("d", Keys.b64u(k.seed)) }
        val proof = Dpop.createDpopProof(CreateDpopProofInput(method = "get", url = "https://api.example.com/a?b=1", privateKey = priv, publicJwk = pub, iat = 1_800_000_000.0))
        val v = VerifyDpopProofOptions(method = "GET", url = "https://api.example.com/a", maxAgeSec = 300.0, nowSec = 1_800_000_001.0, seenJti = seenSet(LinkedHashSet()))
        assertEquals(Dpop.jwkThumbprint(pub), Dpop.verifyDpopProof(proof, v).jkt)
        val bad = proof.substring(0, proof.length - 2) + if (proof.endsWith("AA")) "BB" else "AA"
        v.seenJti = seenSet(LinkedHashSet())
        try {
            Dpop.verifyDpopProof(bad, v)
            fail("a tampered signature must be refused")
        } catch (e: DpopVerificationError) {
            assertTrue(e.code == "signature" || e.code == "malformed")
        }
    }
}
