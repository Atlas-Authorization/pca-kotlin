    @Test fun athFor() = OracleCases.each(m, "athFor") { a -> Dpop.athFor(a[0] as String) }

    @Test fun nonceIssuer() = OracleCases.each(m, "nonceIssuer") { a ->
        val iss = Dpop.createDpopNonceIssuer((a[0] as String?)?.let { Keys.unb64u(it) }, d(a[1]))
        val issued = ArrayList<String>()
        (a[2] as List<*>).map { o ->
            val op = mm(o)!!
            val now = d(op["now"])
            if (op["op"] == "issue") {
                if (now != null && now != Math.rint(now)) throw IllegalArgumentException("not an integer")
                iss.issue(now?.toLong()).also { issued.add(it) }
            } else {
                var nonce = op["nonce"]
                val ref = mm(nonce)
                if (ref != null && ref.containsKey("\$issued")) nonce = issued[d(ref["\$issued"])!!.toInt()]
                iss.check(nonce, now)
            }
        }
    }

    @Test fun replayStore() = OracleCases.each(m, "replayStore") { a ->
        if (a[0] != null && d(a[0]) == null) throw IllegalArgumentException("maxEntries must be a positive integer")
        val st = Dpop.createInMemoryDpopReplayStore(d(a[0]))
        (a[1] as List<*>).map { o ->
            val op = mm(o)!!
            try {
                st.addIfAbsent(op["key"] as String, d(op["exp"])!!, d(op["now"])!!)
            } catch (e: RuntimeException) {
                "throws"
            }
        }
    }

    @Test fun replayConformance() = OracleCases.each(m, "replayConformance") { a ->
        val kind = a[0] as String
        Dpop.runDpopReplayStoreConformance {
            when (kind) {
                "memory" -> Dpop.createInMemoryDpopReplayStore()
                "alwaysTrue" -> DpopReplayStore { _, _, _ -> true }
                "alwaysFalse" -> DpopReplayStore { _, _, _ -> false }
                else -> {
                    val seen = Collections.newSetFromMap(ConcurrentHashMap<String, Boolean>())
                    DpopReplayStore { k, _, _ -> seen.add(k) }
                }
            }
        }
    }

    @Test fun createDpopProof() = OracleCases.each(m, "createDpopProof") { a -> Dpop.createDpopProof(createInput(mm(a[0])!!)) }

    @Test fun createThenVerify() = OracleCases.each(m, "createThenVerify") { a ->
        val i = mm(a[0])!!
        val proof = Dpop.createDpopProof(createInput(i))
        val vo = linkedMapOf<String, Any?>(
            "method" to i["method"], "url" to i["url"], "maxAgeSec" to Json.Num("300"),
            "nowSec" to Json.Num(((d(i["iat"]) ?: 1_800_000_000.0).toLong() + 1).toString()), "seenJti" to ArrayList<Any?>(),
        )
        vo.putAll(mm(a[1])!!)
        val (v, seen) = opts(vo)
        result(Dpop.verifyDpopProof(proof, v), seen)
    }

    @Test fun verifyDpopProof() = OracleCases.each(m, "verifyDpopProof") { a ->
        val (v, seen) = opts(mm(a[1])!!)
