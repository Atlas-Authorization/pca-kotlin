/**
 * Replays the TypeScript-reference vectors of the DPoP / mTLS package: thumbprints, algorithm mapping, URL reduction, replay stores,
 * server nonces, proof creation and verification (every refusal code), mTLS confirmation and the PCActn binding.
 */
@Suppress("UNCHECKED_CAST")
class DpopDiffTest {
    private val m = "ref-dpop"

    private fun mm(o: Any?) = o as? Map<String, Any?>
    private fun s(o: Any?) = o as? String
    private fun d(o: Any?) = Js.num(o)

    /** {"$bytes": b64u} -> ByteArray; a string stays a string. */
    private fun cert(o: Any?): Any? {
        val c = mm(o)
        return if (c != null && c.size == 1 && c["\$bytes"] is String) Keys.unb64u(c["\$bytes"] as String) else o
    }

    private fun store(s: Map<String, Any?>): DpopReplayStore = when (s["kind"]) {
        "memory" -> Dpop.createInMemoryDpopReplayStore(d(s["maxEntries"])).also { st ->
            (s["preload"] as? List<*>)?.forEach { p ->
                val t = p as List<*>
                st.addIfAbsent(t[0] as String, d(t[1])!!, d(t[2])!!)
            }
        }
        "true" -> DpopReplayStore { _, _, _ -> true }
        "false" -> DpopReplayStore { _, _, _ -> false }
        else -> DpopReplayStore { _, _, _ -> throw IllegalStateException("boom") }
    }

    private fun seenSet(set: MutableSet<String>) = object : JtiSeenSet {
        override fun has(jti: String) = jti in set
        override fun add(jti: String) { set.add(jti) }
    }

    /** The verify options a case describes, and the jti set when the case has one. */
    private fun opts(o: Map<String, Any?>): Pair<VerifyDpopProofOptions, MutableSet<String>?> {
        val v = VerifyDpopProofOptions(
            method = s(o["method"]), url = s(o["url"]), maxAgeSec = d(o["maxAgeSec"]) ?: 0.0, expectedJkt = s(o["expectedJkt"]),
            requireReplayStore = o["requireReplayStore"] as? Boolean, nowSec = d(o["nowSec"]), expectedNonce = s(o["expectedNonce"]),
            accessToken = s(o["accessToken"]),
        )
        var seen: MutableSet<String>? = null
        (o["seenJti"] as? List<*>)?.let { l ->
            seen = l.mapTo(LinkedHashSet()) { it as String }
            v.seenJti = seenSet(seen!!)
        }
        mm(o["replayStore"])?.let { v.replayStore = store(it) }
        mm(o["nonceIssuer"])?.let { v.nonceIssuer = Dpop.createDpopNonceIssuer(Keys.unb64u(it["secret"] as String), d(it["ttl"])) }
        return v to seen
    }

    private fun result(r: DpopVerifyResult, seen: Set<String>?) = linkedMapOf<String, Any?>("claims" to r.claims, "jwk" to r.jwk, "jkt" to r.jkt).apply {
        if (seen != null) put("seen", ArrayList(seen))
    }

    private fun createInput(i: Map<String, Any?>) = CreateDpopProofInput(
        method = s(i["method"]), url = s(i["url"]), privateKey = mm(i["privateKey"]), publicJwk = mm(i["publicJwk"]), nonce = s(i["nonce"]),
        ath = s(i["ath"]), iat = d(i["iat"]), jti = s(i["jti"]),
    )

    /** A non-finite maxAgeSec would disable the stale check and a non-finite nowSec would void the window: both are refused. */
    /** ref-dpop-rsa.json.gz is generated by CI (.github/scripts/dpop-rsa-corpus.sh), never committed: required when CI is set, skipped locally. */
    @Test
    fun rsaCorpusIsPresent() {
        val p = net.atlasauth.pca.verifier.BaseOracle.corpusPath("ref-dpop-rsa.json.gz")
        val msg = "RSA DPoP corpus missing: $p (generate with .github/scripts/dpop-rsa-corpus.sh or set PCA_DPOP_RSA_CORPUS)"
        val ci = System.getenv("CI")
        if (ci == "true" || ci == "1") org.junit.Assert.assertTrue(msg, java.nio.file.Files.exists(p))
        else org.junit.Assume.assumeTrue(msg, java.nio.file.Files.exists(p))
    }

    @Test
    fun nonFiniteMaxAgeAndNowRefused() {
        val seed = java.security.MessageDigest.getInstance("SHA-256").digest("dpop-non-finite".toByteArray(Charsets.UTF_8))
        val x = Keys.b64u(Keys.edFromSeed(seed).pub)
        val url = "https://rs.example/r"
        val proof = Dpop.createDpopProof(CreateDpopProofInput(method = "GET", url = url, iat = 1800000000.0,
            privateKey = linkedMapOf("kty" to "OKP", "crv" to "Ed25519", "x" to x, "d" to Keys.b64u(seed)),
            publicJwk = linkedMapOf("kty" to "OKP", "crv" to "Ed25519", "x" to x)))
        fun code(maxAge: Double, now: Double): String = try {
            Dpop.verifyDpopProof(proof, VerifyDpopProofOptions(method = "GET", url = url, maxAgeSec = maxAge, nowSec = now, requireReplayStore = false))
            "ok"
        } catch (e: DpopVerificationError) {
            e.code
        }
        assertEquals("ok", code(300.0, 1800000001.0))
        for (v in listOf(Double.NaN, Double.POSITIVE_INFINITY, Double.NEGATIVE_INFINITY)) {
            assertEquals("maxAgeSec $v", "max_age", code(v, 1800000001.0))
            assertEquals("nowSec $v", "now", code(300.0, v))
        }
    }

