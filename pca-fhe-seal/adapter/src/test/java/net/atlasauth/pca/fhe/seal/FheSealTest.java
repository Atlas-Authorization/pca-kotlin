package net.atlasauth.pca.fhe.seal;

import static org.junit.jupiter.api.Assertions.*;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.InputStreamReader;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.zip.GZIPInputStream;
import net.atlasauth.pca.fhe.seal.FheSeal.EncryptedGate;
import net.atlasauth.pca.fhe.seal.FheSeal.Keyset;
import net.atlasauth.pca.fhe.seal.FheSeal.Policy;
import net.atlasauth.pca.fhe.seal.FheSeal.Verdict;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

/** Replays the node-seal corpus (generated by CI, never committed) and runs a native round trip. -Dpca.fhe.corpus=<path>; -Dpca.fhe.required=true fails instead of skipping. */
class FheSealTest {
  static final boolean REQUIRED = Boolean.getBoolean("pca.fhe.required");

  @BeforeAll
  static void native_() {
    boolean ok = FheSeal.available();
    if (REQUIRED) assertTrue(ok, "libsealc must load (-Dpca.sealc.lib)");
    assumeTrue(ok, "libsealc not available");
  }

  static long[] longs(JsonArray a) {
    long[] r = new long[a.size()];
    for (int i = 0; i < r.length; i++) r[i] = a.get(i).getAsLong();
    return r;
  }

  static Policy policy(double kappa, double budget) {
    double[] w = {0.25, 0.2, 0.2, 0.2, 0.1, 0.05};
    long[] a = new long[6], k = new long[6];
    for (int i = 0; i < 6; i++) {
      a[i] = Math.round(w[i] * 1000);
      k[i] = Math.round(kappa * w[i] * 1000);
    }
    return new Policy(1000, 6, a, k, Math.round(budget * 1e6), kappa);
  }

  @Test
  void evaluatesTheReferenceCiphertextsToTheReferenceResults() throws Exception {
    String path = System.getProperty("pca.fhe.corpus", "");
    if (path.isEmpty()) {
      assertFalse(REQUIRED, "pca.fhe.corpus must point at the node-seal corpus");
      assumeTrue(false, "no corpus");
    }
    JsonObject root;
    try (var in = new InputStreamReader(new GZIPInputStream(Files.newInputStream(Path.of(path))))) {
      root = JsonParser.parseReader(in).getAsJsonObject();
    }
    JsonObject seal = root.getAsJsonObject("seal");
    assertEquals(FheSeal.POLY_MODULUS_DEGREE, seal.get("polyModulusDegree").getAsInt());
    assertEquals(FheSeal.PLAIN_MODULUS, seal.get("plainModulus").getAsLong());
    JsonArray cases = root.getAsJsonArray("cases");
    assertTrue(cases.size() >= 6);
    for (JsonElement e : cases) {
      JsonObject c = e.getAsJsonObject(), p = c.getAsJsonObject("policy");
      String name = c.get("name").getAsString();
      Policy pol = new Policy(p.get("scale").getAsLong(), p.get("dim").getAsLong(), longs(p.getAsJsonArray("weightsScaled")),
          longs(p.getAsJsonArray("kappaWeightsScaled")), p.get("budgetScaled").getAsLong(), p.get("kappa").getAsDouble());
      EncryptedGate g = FheSeal.evalRiskGate(root.get("publicKey").getAsString(), root.get("galoisKeys").getAsString(), c.get("encInputs").getAsString(), pol);
      // deterministic evaluation: byte-equal once both are re-saved uncompressed
      assertEquals(FheSeal.canonicalCipher(c.get("encRiskRaw").getAsString()), FheSeal.canonicalCipher(g.encRiskRaw()), name);
      assertEquals(FheSeal.canonicalCipher(c.get("encSlack").getAsString()), FheSeal.canonicalCipher(g.encSlack()), name);
    }
  }

  @Test
  void nativeRoundTripMatchesPlaintextArithmetic() {
    Keyset keys = FheSeal.keygen();
    Object[][] cases = {{new long[] {100, 900, 100, 100, 100, 100}, 1.0, 0.6}, {new long[] {1000, 1000, 1000, 1000, 1000, 1000}, 1.0, 0.5}, {new long[6], 1.5, 0.25}};
    for (Object[] t : cases) {
      long[] x = (long[]) t[0];
      Policy p = policy((double) t[1], (double) t[2]);
      EncryptedGate g = FheSeal.evalRiskGate(keys.publicKey(), keys.galoisKeys(), FheSeal.encryptRiskInputs(keys.publicKey(), x), p);
      Verdict v = FheSeal.decryptVerdict(keys.secretKey(), g.encRiskRaw(), g.encSlack(), p);
      long raw = 0, kr = 0;
      for (int i = 0; i < 6; i++) {
        raw += p.weightsScaled()[i] * x[i];
        kr += p.kappaWeightsScaled()[i] * x[i];
      }
      assertEquals(new Verdict(raw, p.budgetScaled() - kr, p.budgetScaled() - kr >= 0), v);
    }
  }

  @Test
  void allZeroWeightsEvaluateToZero() {
    Keyset keys = FheSeal.keygen();
    Policy p = new Policy(1000, 6, new long[6], new long[6], 5000, 1);
    EncryptedGate g = FheSeal.evalRiskGate(keys.publicKey(), keys.galoisKeys(), FheSeal.encryptRiskInputs(keys.publicKey(), new long[] {5, 5, 5, 5, 5, 5}), p);
    assertEquals(new Verdict(0, 5000, true), FheSeal.decryptVerdict(keys.secretKey(), g.encRiskRaw(), g.encSlack(), p));
  }

  @Test
  void wrongKeyFailsClosed() {
    Keyset a = FheSeal.keygen(), b = FheSeal.keygen();
    Policy p = policy(1, 0.6);
    EncryptedGate g = FheSeal.evalRiskGate(a.publicKey(), a.galoisKeys(), FheSeal.encryptRiskInputs(a.publicKey(), new long[] {1, 2, 3, 4, 5, 6}), p);
    var e = assertThrows(IllegalStateException.class, () -> FheSeal.decryptVerdict(b.secretKey(), g.encRiskRaw(), g.encSlack(), p));
    assertTrue(e.getMessage().contains("noise budget"));
  }

  @Test
  void malformedBlobsAndPoliciesAreRefused() {
    Keyset keys = FheSeal.keygen();
    String good = FheSeal.encryptRiskInputs(keys.publicKey(), new long[] {1, 2, 3, 4, 5, 6});
    for (String bad : new String[] {good.substring(0, good.length() - 8), good + "AAAA", "AAAA", "A".repeat(64)})
      assertThrows(IllegalArgumentException.class, () -> FheSeal.assertSealBlob(bad, "x"));
    long[] z = new long[6];
    for (Policy bad : new Policy[] {new Policy(1000, 5, z, z, 0, 1), new Policy(1000, 6, z, z, FheSeal.SIGNED_BOUND, 1), new Policy(0, 6, z, z, 0, 1),
        new Policy(1000, 6, new long[5], z, 0, 1), new Policy(1000, 6, z, z, Long.MIN_VALUE, 1), null})
      assertThrows(IllegalArgumentException.class, () -> FheSeal.requirePolicy(bad));
    assertThrows(IllegalArgumentException.class, () -> FheSeal.encryptRiskInputs("x", new long[] {-1, 0, 0, 0, 0, 0}));
  }
}
