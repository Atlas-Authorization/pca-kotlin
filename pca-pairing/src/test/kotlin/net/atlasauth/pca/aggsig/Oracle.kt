package net.atlasauth.pca.aggsig

import java.io.BufferedReader
import java.io.File
import java.io.InputStreamReader
import java.util.zip.GZIPInputStream
import net.atlasauth.pca.verifier.Json
import net.atlasauth.pca.verifier.Keys
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue

/**
 * Replays a TypeScript-reference oracle (test-data/<module>.json.gz: a header, then one {fn, name, args, out} case per line).
 * Bytes are {"$bytes": b64url}; {"$throws": ...} means the native must throw. Results compare as canonical JSON.
 */
@Suppress("UNCHECKED_CAST")
object Oracle {
    /** ref-abe-gen.json.gz is generated by CI (never committed): next to the main corpus, PCA_SECRET_CORPUS_DIR overrides the directory. */
    fun genFile(module: String): File {
        val env = System.getenv("PCA_SECRET_CORPUS_DIR")
        return File(if (!env.isNullOrEmpty()) File(env) else File("test-data").absoluteFile, "$module-gen.json.gz")
    }

    fun of(module: String, fn: String): List<Map<String, Any?>> {
        val out = ArrayList<Map<String, Any?>>()
        val head = "{\"fn\":" + Json.canonicalize(fn) + ","
        val paths = listOf(File("test-data/$module.json.gz")) + if (module == "ref-abe" && genFile(module).exists()) listOf(genFile(module)) else emptyList()
        for (f in paths) BufferedReader(InputStreamReader(GZIPInputStream(f.inputStream()), Charsets.UTF_8)).use { r ->
            while (true) {
                var line = r.readLine() ?: break
                if (!line.startsWith(head)) continue
                if (line.endsWith(",")) line = line.substring(0, line.length - 1)
                out.add(unbbs(Json.parseLenient(line)) as Map<String, Any?>)
            }
        }
        assertFalse("no oracle cases for $module/$fn", out.isEmpty())
        return out
    }

    /** The BBS corpus carries no signing keys: {"$bbssk": n} stands for KeyGen(32 bytes of n, empty key info), as 64 lowercase hex digits. */
    private fun unbbs(v: Any?): Any? = when (v) {
        is Map<*, *> ->
            if (v.size == 1 && (v["\$bbssk"] is Json.Num || v["\$bbssk"] is Number)) {
                val fill = (v["\$bbssk"] as? Json.Num)?.raw?.toInt() ?: (v["\$bbssk"] as Number).toInt() // the parser yields Json.Num, not a Number
                String.format("%064x", net.atlasauth.pca.bbs.Bbs.keyGen(ByteArray(32) { fill.toByte() }))
            }
            else LinkedHashMap<String, Any?>().also { out -> for ((k, x) in v) out[k as String] = unbbs(x) }
        is List<*> -> v.map { unbbs(it) }
        else -> v
    }

    fun bytes(o: Any?): ByteArray {
        val v = (o as? Map<String, Any?>)?.get("\$bytes")
        if (v is String) return Keys.unb64u(v)
        throw IllegalArgumentException("not a \$bytes value: $o")
    }

    fun bytesList(o: Any?): List<ByteArray> = (o as List<Any?>).map { bytes(it) }

    fun toJson(v: Any?): Any? = when (v) {
        is ByteArray -> linkedMapOf<String, Any?>("\$bytes" to Keys.b64u(v))
        is Map<*, *> -> LinkedHashMap<String, Any?>().also { out -> for ((k, x) in v) out[k as String] = toJson(x) }
        is List<*> -> v.map { toJson(it) }
        else -> v
    }

    fun each(module: String, fn: String, f: (List<Any?>) -> Any?) {
        val bad = ArrayList<String>()
        for (c in of(module, fn)) {
            val want = c["out"]
            val wantThrow = want is Map<*, *> && want.containsKey("\$throws")
            var got: Any? = null
            var err: Throwable? = null
            try { got = f(c["args"] as List<Any?>) } catch (t: Throwable) { err = t }
            if (wantThrow) {
                if (err == null) bad.add("${c["name"]}: want a throw, got ${Json.canonicalize(toJson(got))}")
            } else if (err != null) {
                bad.add("${c["name"]}: unexpected $err")
            } else {
                val a = Json.canonicalize(want)
                val b = Json.canonicalize(toJson(got))
                if (a != b) bad.add("${c["name"]}\n  want $a\n  got  $b")
            }
        }
        assertTrue("${bad.size} divergent case(s) of $fn:\n" + bad.take(30).joinToString("\n"), bad.isEmpty())
    }
}
